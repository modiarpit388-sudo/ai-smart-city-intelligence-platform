import { useRef, useState } from 'react'
import { Database, Download, RefreshCw, Upload } from 'lucide-react'
import { api } from '../api'
import { ErrorBox, fmtTime, Loader, Panel, useFetch } from '../ui'

export default function Datasets() {
  const { data, error, loading, reload } = useFetch('/api/admin/datasets')
  const [msg, setMsg] = useState('')
  const file = useRef(null)
  const [target, setTarget] = useState(null)
  const ingest = async () => { const r = await api.post('/api/admin/datasets/ingest'); const n = Object.values(r.added).reduce((a, b) => a + b, 0); setMsg(n ? `Ingested ${n.toLocaleString()} new rows.` : 'Data is already up to date.'); reload() }
  const upload = async (e) => {
    const f = e.target.files[0]; if (!f || !target) return
    const fd = new FormData(); fd.append('file', f)
    try { const r = await api.post(`/api/admin/datasets/${target}/import`, fd); setMsg(`Imported ${r.imported} rows into ${target}.`); reload() } catch (ex) { setMsg('Import failed: ' + ex.message) }
    e.target.value = ''
  }
  if (error) return <ErrorBox error={error} retry={reload} />
  if (loading && !data) return <Loader />
  return (
    <div className="stack" style={{ gap: 18 }}>
      <input ref={file} type="file" accept=".csv" hidden onChange={upload} />
      <Panel title="Monitoring datasets" icon={Database} flush right={<button className="btn primary sm" onClick={ingest}><RefreshCw />Ingest latest readings</button>}>
        <div className="table-wrap" style={{ padding: 8 }}>
          <table className="t"><thead><tr><th>Table</th><th className="right">Rows</th><th>From</th><th>To</th><th>Columns</th><th /></tr></thead>
            <tbody>{data.datasets.map((d) => (
              <tr key={d.table}><td><b>{d.table}</b></td><td className="num">{d.rows.toLocaleString()}</td><td className="mute">{fmtTime(d.first)}</td><td className="mute">{fmtTime(d.last)}</td>
                <td className="dim" style={{ maxWidth: 320, fontSize: 11 }}>{d.columns.join(', ')}</td>
                <td className="right"><div className="row" style={{ justifyContent: 'flex-end' }}>
                  <button className="btn sm" onClick={() => api.download(`/api/admin/datasets/${d.table}/export?limit=50000`, `${d.table}.csv`)}><Download />CSV</button>
                  <button className="btn sm" onClick={() => { setTarget(d.table); file.current.click() }}><Upload />Import</button></div></td></tr>))}</tbody></table>
        </div>
        {msg && <div className="pill-note" style={{ margin: 12 }}>{msg}</div>}
      </Panel>
      <div className="pill-note">Data is synthetic and generated by realistic simulators (rush-hour profiles, CPCB AQI formula, weather-driven demand). To use real data, import CSVs with the same column names — or replace <code>backend/app/simulation</code> with a connector to your sensors / open-data APIs. After importing, retrain the models in <b>ML Models</b>.</div>
    </div>
  )
}
