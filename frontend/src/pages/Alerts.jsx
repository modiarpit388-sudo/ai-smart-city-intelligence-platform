import { useState } from 'react'
import { AlertTriangle, Info, OctagonAlert, RefreshCw } from 'lucide-react'
import { motion } from 'framer-motion'
import { api } from '../api'
import { useAuth } from '../auth'
import { Badge, ErrorBox, fmtTime, Loader, Panel, useFetch } from '../ui'

const ICON = { critical: OctagonAlert, warning: AlertTriangle, info: Info }
const TYPES = ['all', 'traffic', 'aqi', 'accident', 'waste', 'water', 'electricity', 'complaints']

export default function Alerts() {
  const { user } = useAuth()
  const { data, error, loading, reload } = useFetch('/api/alerts', [], { interval: 60000 })
  const [type, setType] = useState('all')
  const [busy, setBusy] = useState(false)
  const refresh = async () => { setBusy(true); try { await api.post('/api/alerts/refresh'); reload() } finally { setBusy(false) } }
  if (error) return <ErrorBox error={error} retry={reload} />
  if (loading && !data) return <Loader />
  const items = data.alerts.filter((a) => type === 'all' || a.type === type)
  const count = (s) => data.alerts.filter((a) => a.severity === s).length
  return (
    <div className="stack" style={{ gap: 18 }}>
      <div className="row between wrap">
        <div className="tabs">{TYPES.map((t) => <button key={t} className={`tab ${type === t ? 'on' : ''}`} onClick={() => setType(t)}>{t}</button>)}</div>
        <div className="row wrap"><Badge level="critical">{count('critical')} critical</Badge><Badge level="warning">{count('warning')} warning</Badge><Badge level="info">{count('info')} info</Badge>
          {user.role !== 'citizen' && <button className="btn sm" onClick={refresh} disabled={busy}><RefreshCw />Recompute</button>}</div>
      </div>
      <Panel title="Predictive alerts" icon={AlertTriangle}>
        {items.length === 0 ? <div className="empty">No alerts in this category.</div> : items.map((a, i) => {
          const Ico = ICON[a.severity] || Info
          return (
            <motion.div key={a.id} className={`alert-card ${a.severity}`} initial={{ opacity: 0, x: -16 }} animate={{ opacity: 1, x: 0 }} transition={{ delay: i * 0.04 }}>
              <Ico />
              <div style={{ flex: 1 }}><b>{a.title}</b><p>{a.message}</p><div className="dim" style={{ fontSize: 11, marginTop: 4 }}>{a.area} · {a.department || 'All departments'} · {fmtTime(a.created_at)}</div></div>
              <Badge level={a.severity} />
            </motion.div>)
        })}
        <div className="pill-note">Alerts are generated by rules on top of ML forecasts (e.g. traffic index ≥ 80 for 2+ hours, predicted AQI ≥ 180, waste 15% above normal) and pushed to the relevant department and to citizens of the affected area.</div>
      </Panel>
    </div>
  )
}
